"""Native storage and independent SGLang allocation-shape oracles.

Expected byte counts below come from pinned checkpoint indices / upstream
buffer shapes; they are not generated by InferFit's memory functions.
"""
import copy
from dataclasses import replace
from importlib.resources import files
import json
from pathlib import Path
import subprocess
import sys
import unittest

from inferfit import (Hardware, Parallelism, RuntimeProfile, Workload, check,
    from_config, kv_per_token, load_model, load_model_profile, logical_weight_bytes,
    model_profile_to_dict, optimize_pipeline, search, UnsupportedModelError)
from inferfit.engines import EngineAdapter, SglangAdapter, VllmAdapter
from inferfit.states import get_state_model
from inferfit.weights import storage_bytes


class NativeModelTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.qwen = load_model("qwen3.8-flash-next-fp8")
        cls.flash = load_model("deepseek-v4-flash")
        cls.pro = load_model("deepseek-v4-pro")
        cls.runtime = RuntimeProfile.sglang()

    def run_check(self, model=None, **kwargs):
        model = self.flash if model is None else model
        values = dict(runtime=self.runtime, parallelism=Parallelism(tp=4, ep=4, num_gpus=4),
                      workload=Workload(block_size=256), weight_quantization="native", kv_quantization="fp8")
        values.update(kwargs)
        return check(model, **values)

    def test_engines_have_neutral_contracts(self):
        self.assertTrue(issubclass(SglangAdapter, EngineAdapter))
        self.assertTrue(issubclass(VllmAdapter, EngineAdapter))
        self.assertFalse(issubclass(SglangAdapter, VllmAdapter))
        self.assertIsInstance(SglangAdapter(), EngineAdapter)

    def test_single_upstream_contract_and_removed_compatibility_factories(self):
        from inferfit.engine_versions import SGLANG_VERSION
        from inferfit.engines import get_adapter
        self.assertEqual(SGLANG_VERSION, "0.5.23")
        current = RuntimeProfile.sglang()
        self.assertEqual(current.version, SGLANG_VERSION)
        self.assertEqual(get_adapter(current).version, SGLANG_VERSION)
        for removed in ("sglang_legacy", "sglang_current", "sglang_flagship"):
            self.assertFalse(hasattr(RuntimeProfile, removed))
        self.assertEqual(self.run_check(runtime=current).status, "pass")

    def test_checkpoint_total_and_base_bytes_are_exact(self):
        cases = [(self.qwen, "qwen38-flash-next-fp8", 185502232570, 2698026496, 152089, 131),
                 (self.flash, "deepseek-v4-flash", 159609485896, 3593787756, 69187, 46),
                 (self.pro, "deepseek-v4-pro", 864704792696, 13956587692, 145116, 64)]
        for model, stem, total, mtp, tensors, shards in cases:
            with self.subTest(stem=stem):
                meta = json.loads(files("inferfit").joinpath("data", stem + "-metadata.json").read_text())
                self.assertEqual(meta["checkpoint_bytes"], total)
                self.assertEqual(meta["mtp_bytes"], mtp)
                self.assertEqual(meta["tensor_count"], tensors)
                self.assertEqual(meta["shard_count"], shards)
                self.assertFalse(meta["tensor_payload_downloaded"])
                self.assertEqual(sum(storage_bytes(tuple(t["shape"]), t["dtype"]) * t.get("multiplicity", 1) for t in meta["tensors"]), total)
                self.assertEqual(logical_weight_bytes(model, "native"), total - mtp)
                self.assertEqual(logical_weight_bytes(model, "fp8"), total - mtp)
                self.assertFalse(any(t.name.startswith("mtp.") for t in model.tensors))

    def test_qwen_fp8_has_native_exclusions_and_one_ngram_scale(self):
        ts = self.qwen.tensors
        table = next(t for t in ts if t.name.endswith("ngram_embedding.weight"))
        self.assertEqual(table.dtype, "F8_E4M3")
        self.assertEqual(storage_bytes(table.shape, table.dtype), 51200245760)
        self.assertEqual(sum(t.name.endswith("ngram_embedding.weight_scale") for t in ts), 1)
        experts = [t for t in ts if "{expert}" in t.name]
        self.assertTrue(all(t.multiplicity == 512 and not t.quantizable for t in experts))
        self.assertTrue(any(t.dtype == "BF16" and ".shared_expert." in t.name for t in ts))
        self.assertTrue(any(t.dtype == "BF16" and ".linear_attn." in t.name for t in ts))

    def test_qwen_scale_cast_and_native_ep(self):
        plan = Parallelism(tp=4, ep=4, num_gpus=4)
        result = self.run_check(self.qwen, parallelism=plan, workload=Workload(), kv_quantization="bf16")
        self.assertEqual(result.status, "pass")
        self.assertEqual(result.ranks[0].kv_bytes_per_token, 13056)
        self.assertEqual(result.ranks[0].weight_bytes, 47528128794)
        # SGLang's FP8 MoE converts source BF16 block scales to FP32.
        scale = next(t for t in self.qwen.tensors if t.name.endswith(".weight_scale_inv"))
        self.assertEqual(SglangAdapter().tensor_dtype(scale), "F32")
        bad = self.run_check(self.qwen, parallelism=replace(plan, ep=1), workload=Workload(), kv_quantization="bf16")
        self.assertEqual(bad.status, "unsupported")
        self.assertIn("EP=TP", " ".join(bad.reasons))

    def test_native_format_cannot_silently_become_bf16(self):
        for model in (self.qwen, self.flash, self.pro):
            with self.assertRaisesRegex(ValueError, "Native"):
                logical_weight_bytes(model, "bf16")
            self.assertEqual(self.run_check(model, weight_quantization="bf16").status, "unsupported")
        unknown = replace(self.flash, provenance={**self.flash.provenance, "native_quantization": "uninspected-layout"})
        rejected = self.run_check(unknown)
        self.assertEqual(rejected.status, "unsupported")
        self.assertIn("no inspected contract", " ".join(rejected.reasons))

    def test_v4_packed_expert_shapes_and_native_scales(self):
        ts = {t.name: t for t in self.flash.tensors}
        w = ts["layers.0.ffn.experts.{expert}.w1.weight"]
        s = ts["layers.0.ffn.experts.{expert}.w1.scale"]
        self.assertEqual((w.shape, w.dtype, w.multiplicity), ((2048, 2048), "I8", 256))
        self.assertEqual((s.shape, s.dtype), ((2048, 128), "F8_E8M0"))
        self.assertEqual(SglangAdapter().tensor_dtype(s), "F8_E8M0")
        self.assertEqual(storage_bytes(w.shape, w.dtype), 4194304)  # two FP4 / byte
        self.assertEqual(storage_bytes(s.shape, s.dtype), 262144)  # one E8M0 / 32 weights

    def test_v4_drops_only_mtp_compression_ratio(self):
        self.assertEqual(len(self.flash.config["compress_ratios"]), 43)
        self.assertEqual(self.flash.config["compress_ratios"].count(4), 21)
        self.assertEqual(self.flash.config["compress_ratios"].count(128), 20)
        self.assertEqual(len(self.pro.config["compress_ratios"]), 61)
        self.assertEqual(self.pro.config["compress_ratios"].count(128), 31)

    def test_v4_buffer_shapes_independent_oracle(self):
        rank = self.run_check().ranks[0]
        # Source shapes at 8192 full slots, page256, C4 page64, C128 page2.
        expected = {"swa_paged_kv": 212509440, "c4_compressed_kv": 28304640,
                    "c4_index_keys_and_scales": 6386688, "c128_compressed_kv": 5529600}
        self.assertEqual(rank.kv_allocation_breakdown, expected)
        self.assertEqual(rank.kv_required_bytes, sum(expected.values()))
        self.assertEqual(rank.runtime_breakdown["c4_compressor_state"], 46104576)
        self.assertEqual(rank.runtime_breakdown["c4_indexer_compressor_state"], 11526144)
        self.assertEqual(rank.runtime_breakdown["c128_compressor_state"], 41943040)
        self.assertEqual(rank.runtime_breakdown["v4_rope_frequency_tables"], 536870912)
        self.assertEqual(rank.kv_allocated_tokens, 8192)

    def test_v4_cache_is_replicated_and_rate_is_amortized(self):
        rates = [kv_per_token(self.flash, runtime=self.runtime, tp=tp, kv_quantization="fp8")["total"] for tp in (1, 2, 4, 8)]
        self.assertEqual(rates, [29055] * 4)
        result = self.run_check()
        self.assertIn("amortized", result.summary["kv_rate_semantics"])
        # Full-token-rate multiplication omits the extra pages and fixed rings.
        self.assertGreater(result.ranks[0].kv_required_bytes, 29055 * 8192)

    def test_v4_pool_page_rounding_and_minimum(self):
        a = self.run_check(workload=Workload(context_tokens=8191, block_size=256)).ranks[0]
        b = self.run_check(workload=Workload(context_tokens=8192, block_size=256)).ranks[0]
        c = self.run_check(workload=Workload(context_tokens=8193, block_size=256)).ranks[0]
        self.assertEqual(a.kv_required_bytes, b.kv_required_bytes)
        self.assertGreater(c.kv_required_bytes, b.kv_required_bytes)
        tiny = self.run_check(workload=Workload(context_tokens=1, block_size=256))
        self.assertEqual(tiny.ranks[0].kv_allocated_tokens, 512)
        self.assertEqual(tiny.summary["engine_args"]["max_total_tokens"], 512)

    def test_v4_concurrency_and_offline_state_growth(self):
        a = self.run_check().ranks[0]
        b = self.run_check(workload=Workload(concurrency_per_dp=2, block_size=256)).ranks[0]
        self.assertGreater(b.runtime_breakdown["c128_compressor_state"], a.runtime_breakdown["c128_compressor_state"])
        longer = self.run_check(workload=Workload(context_tokens=16384, block_size=256)).ranks[0]
        self.assertEqual(a.runtime_breakdown["c128_compressor_state"], longer.runtime_breakdown["c128_compressor_state"])
        self.assertGreater(longer.runtime_breakdown["c4_compressor_state"], a.runtime_breakdown["c4_compressor_state"])

    def test_v4_exact_capacity_reprices_all_pools(self):
        result = self.run_check()
        rank = result.ranks[0]
        state = get_state_model(self.flash)
        p, w = result.parallelism, Workload(block_size=256)
        fixed = rank.runtime_peak_bytes - sum(state.allocate(self.flash, p, w, self.runtime, "fp8", 0, 43).runtime_parts.values())
        available = rank.budget_bytes - rank.weight_bytes - fixed
        n = rank.kv_capacity_tokens
        self.assertLessEqual(state.allocate(self.flash, p, w, self.runtime, "fp8", 0, 43, tokens=n).total_bytes, available)
        self.assertGreater(state.allocate(self.flash, p, w, self.runtime, "fp8", 0, 43, tokens=n+256).total_bytes, available)

    def test_v4_peak_boundary(self):
        peak = self.run_check().ranks[0].peak_bytes
        h = Hardware(memory_bytes=peak, utilization=1, safety_margin_bytes=0)
        self.assertEqual(self.run_check(hardware=h).status, "pass")
        self.assertEqual(self.run_check(hardware=replace(h, memory_bytes=peak-1)).status, "fail")

    def test_v4_contract_emits_native_backend_and_pool_controls(self):
        result = self.run_check()
        args, env = result.summary["engine_args"], result.summary["engine_env"]
        self.assertEqual(args["moe_runner_backend"], "flashinfer_mxfp4")
        self.assertEqual(args["dsv4_attn_backend"], "flashmla")
        self.assertEqual(args["swa_full_tokens_ratio"], 1.0)
        self.assertEqual(args["page_size"], 256)
        self.assertEqual(env["SGLANG_DSV4_COMPRESS_STATE_DTYPE"], "float32")
        self.assertEqual(env["SGLANG_DSV4_FP4_DEQUANT"], "false")
        self.assertFalse(result.summary["deployment_verified"])

    def test_v4_rejects_other_versions_precision_and_geometry(self):
        for values in [dict(runtime=RuntimeProfile.sglang(version="0.5.10")), dict(runtime=RuntimeProfile()),
                       dict(kv_quantization="bf16"), dict(workload=Workload()),
                       dict(hardware=Hardware(compute_capability=80)),
                       dict(hardware=Hardware(compute_capability=100)),
                       dict(parallelism=Parallelism(tp=4, ep=2, num_gpus=4)),
                       dict(parallelism=Parallelism(tp=4, dp=2, ep=8, num_gpus=8))]:
            with self.subTest(values=values):
                self.assertEqual(self.run_check(**values).status, "unsupported")

    def test_v4_configs_are_pinned_and_v41_is_separate(self):
        config = json.loads(files("inferfit").joinpath("data/deepseek-v4-flash-config.json").read_text())
        self.assertEqual(from_config(config).architecture, "dsv4")
        config["compress_ratios"][2] = 128
        with self.assertRaisesRegex(UnsupportedModelError, "pinned"):
            from_config(config)
        with self.assertRaises(UnsupportedModelError):
            load_model("deepseek-v4.1-flash-1017")

    def test_native_profiles_roundtrip_and_disallow_double_quantization(self):
        for model in (self.qwen, self.flash, self.pro):
            document = model_profile_to_dict(model)
            rebuilt = load_model_profile(document)
            self.assertEqual(logical_weight_bytes(rebuilt, "native"), logical_weight_bytes(model, "native"))
            self.assertEqual(self.run_check(rebuilt).status, self.run_check(model).status)
            bad = copy.deepcopy(document)
            next(row for row in bad["tensors"] if row["dtype"] in {"I8", "F8_E4M3"})["quantizable"] = True
            with self.assertRaisesRegex(ValueError, "Native"):
                load_model_profile(bad)

    def test_pro_pipeline_16_card_candidate(self):
        result = self.run_check(self.pro, parallelism=Parallelism(tp=8, ep=8, pp=2, num_gpus=16))
        self.assertEqual(result.status, "pass")
        self.assertEqual(result.summary["nodes_required"], 2)
        self.assertEqual(result.summary["stage_layers"], [30, 31])
        self.assertEqual(result.summary["engine_env"]["SGLANG_PP_LAYER_PARTITION"], "30,31")

    def test_native_repacking_peak_includes_resident_buffers(self):
        result = self.run_check(self.pro, hardware=Hardware(memory_bytes=10**15),
                                parallelism=Parallelism(tp=1, ep=1, pp=2, num_gpus=2))
        workspace = result.summary["load_workspace_bytes_per_rank"]
        self.assertGreater(workspace, self.runtime.load_workspace_bytes)
        rank = result.ranks[0]
        self.assertEqual(rank.load_peak_bytes - rank.weight_bytes,
            workspace + self.runtime.cuda_context_bytes + self.runtime.communication_bytes + self.runtime.allocator_bytes
            + rank.runtime_breakdown["v4_rope_frequency_tables"] + rank.runtime_breakdown["v4_auxiliary_buffer_envelope"])

    def test_packaged_native_cli_examples(self):
        root = Path(__file__).resolve().parents[1]
        for stem in ("qwen38-flash-next-fp8", "deepseek-v4-flash", "deepseek-v4-pro"):
            command = [sys.executable, "-m", "inferfit", "check", str(root / "examples/flagships" / (stem + "-check.json"))]
            process = subprocess.run(command, text=True, capture_output=True)
            self.assertEqual(process.returncode, 0, process.stderr)
            output = json.loads(process.stdout)
            self.assertEqual(output["status"], "pass")
            self.assertFalse(output["summary"]["deployment_verified"])

    def test_v4_pp_optimizer_matches_all_two_stage_splits(self):
        plan = Parallelism(tp=2, ep=2, pp=2, num_gpus=4)
        kwargs = dict(hardware=Hardware(memory_bytes=10**15), runtime=self.runtime,
                      workload=Workload(block_size=256), weight_quantization="native", kv_quantization="fp8")
        peaks = [max(r.peak_bytes for r in check(self.flash, parallelism=replace(plan, stage_layers=(i, 43-i)), **kwargs).ranks) for i in range(1,43)]
        result = optimize_pipeline(self.flash, parallelism=plan, **kwargs)
        self.assertEqual(max(r.peak_bytes for r in result.ranks), min(peaks))

    def test_qwen_and_v4_search_produce_candidates(self):
        for model, kv, page, minimum in [(self.qwen, "bf16", 64, 4), (self.flash, "fp8", 256, 4)]:
            result = search(model, runtime=self.runtime, weight_quantization="native", kv_quantization=kv,
                            workload=Workload(block_size=page), tp_values=[1,2,4,8], dp_values=[1], pp_values=[1], max_gpus=8)
            self.assertEqual(result.minimum_num_gpus, minimum)
            self.assertTrue(all(c.parallelism.ep == c.parallelism.tp for c in result.candidates))

    def test_native_pd_does_not_reuse_ordinary_kv_transfer(self):
        from inferfit import check_pd, PDPool
        result = check_pd(self.flash, prefill=PDPool(tuple("abcd")), decode=PDPool(tuple("efgh")))
        self.assertEqual(result.status, "unsupported")


